// Generate all icons from one transparent source PNG.
// Usage: swift scripts/make-icons.swift resources/modelpull-logo.png
// Outputs:
//   build/icons/AppIcon.icns            macOS app icon (glyph on dark rounded square, Apple 1024 grid)
//   build/icons/linux-256.png           Linux app-menu icon (same look)
//   src/ModelPullApp/LogoImage.swift    small transparent glyph (64 px) embedded for the SwiftUI header
//   src/ModelPullWeb/LogoImage.swift    same glyph embedded for the web page header + favicon
import AppKit

let args = CommandLine.arguments
guard args.count == 2, let src = NSImage(contentsOfFile: args[1]) else {
    FileHandle.standardError.write(Data("usage: swift scripts/make-icons.swift <source.png>\n".utf8)); exit(1)
}
let fm = FileManager.default
let out = URL(fileURLWithPath: "build/icons")
let iconset = out.appendingPathComponent("AppIcon.iconset")
try? fm.removeItem(at: iconset)
try! fm.createDirectory(at: iconset, withIntermediateDirectories: true)

/// Draw at exact pixel size. `tile`: dark rounded square behind the glyph (app icon); else glyph only.
func png(_ px: Int, tile: Bool) -> Data {
    let rep = NSBitmapImageRep(bitmapDataPlanes: nil, pixelsWide: px, pixelsHigh: px, bitsPerSample: 8, samplesPerPixel: 4,
                               hasAlpha: true, isPlanar: false, colorSpaceName: .deviceRGB, bytesPerRow: 0, bitsPerPixel: 0)!
    NSGraphicsContext.saveGraphicsState()
    NSGraphicsContext.current = NSGraphicsContext(bitmapImageRep: rep)
    NSGraphicsContext.current!.imageInterpolation = .high
    let s = CGFloat(px)
    var glyph = NSRect(x: 0, y: 0, width: s, height: s)
    if tile {
        // Apple macOS icon grid: 824/1024 body, ~185/1024 corner radius.
        let inset = s * 100 / 1024
        let body = NSRect(x: inset, y: inset, width: s - 2 * inset, height: s - 2 * inset)
        let path = NSBezierPath(roundedRect: body, xRadius: s * 185 / 1024, yRadius: s * 185 / 1024)
        NSColor(white: 0.055, alpha: 1).setFill()
        path.fill()
        NSColor(white: 1, alpha: 0.08).setStroke()
        path.lineWidth = max(1, s / 512)
        path.stroke()
        glyph = body.insetBy(dx: body.width * 0.08, dy: body.height * 0.08)
    }
    src.draw(in: glyph, from: .zero, operation: .sourceOver, fraction: 1)
    NSGraphicsContext.restoreGraphicsState()
    return rep.representation(using: .png, properties: [:])!
}

for (name, px) in [("16x16", 16), ("16x16@2x", 32), ("32x32", 32), ("32x32@2x", 64), ("128x128", 128),
                   ("128x128@2x", 256), ("256x256", 256), ("256x256@2x", 512), ("512x512", 512), ("512x512@2x", 1024)] {
    try! png(px, tile: true).write(to: iconset.appendingPathComponent("icon_\(name).png"))
}
try! png(256, tile: true).write(to: out.appendingPathComponent("linux-256.png"))

let glyphB64 = png(64, tile: false).base64EncodedString()
for target in ["ModelPullApp", "ModelPullWeb"] {
    let swift = """
    // GENERATED by scripts/make-icons.swift from resources/modelpull-logo.png — do not edit.
    import Foundation

    enum LogoImage {
        /// 64×64 transparent PNG (shown at 16–20 pt).
        static let png = Data(base64Encoded: "\(glyphB64)")!
    }

    """
    try! swift.write(toFile: "src/\(target)/LogoImage.swift", atomically: true, encoding: .utf8)
}
print("iconset + linux icon in build/icons, LogoImage.swift in both UI targets (glyph \(glyphB64.count / 1024) KB base64)")
